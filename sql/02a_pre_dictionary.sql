-- SmartFin Pre-Dictionary
-- Purpose:
-- 1. Store common raw financial labels found in annual reports.
-- 2. Map them to SmartFin canonical financial concepts.
-- 3. Provide the first deterministic layer for automatic PDF standardization.
--
-- This table is intentionally separate from ITEM_MAPPING:
-- ITEM_MAPPING stores approved mappings used by the database;
-- PRE_DICTIONARY stores the reusable vocabulary used by the ingestion pipeline.

CREATE TABLE PRE_DICTIONARY (
    PRE_DICT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RAW_LABEL VARCHAR2(500) NOT NULL,
    STANDARD_ITEM_CODE VARCHAR2(50) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    STATEMENT_TYPE VARCHAR2(50),
    ALIAS_TYPE VARCHAR2(30),
    MAPPING_CONFIDENCE NUMBER(5,4) DEFAULT 1.0 NOT NULL,
    NOTES VARCHAR2(1000),
    CONSTRAINT UQ_PRE_DICT_LABEL UNIQUE (RAW_LABEL),
    CONSTRAINT CK_PRE_DICT_CONF CHECK (MAPPING_CONFIDENCE BETWEEN 0 AND 1)
);

