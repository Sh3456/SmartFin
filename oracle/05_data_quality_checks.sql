-- SmartFin data import checks — Oracle SQL
-- Run only after importing all seven CSV files.

-- 1. Confirm that each CSV was loaded. Compare the counts with the source.
SELECT 'LOCATIONS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM LOCATIONS
UNION ALL SELECT 'DEVICES', COUNT(*) FROM DEVICES
UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM CUSTOMERS
UNION ALL SELECT 'MERCHANTS', COUNT(*) FROM MERCHANTS
UNION ALL SELECT 'TRANSACTIONS', COUNT(*) FROM TRANSACTIONS
UNION ALL SELECT 'CHARGEBACKS', COUNT(*) FROM CHARGEBACKS
UNION ALL SELECT 'FRAUD_ALERTS', COUNT(*) FROM FRAUD_ALERTS
ORDER BY TABLE_NAME;

-- 2. Inspect transaction date range and basic amount statistics.
SELECT MIN(TRANSACTION_TIMESTAMP) AS FIRST_TRANSACTION,
       MAX(TRANSACTION_TIMESTAMP) AS LAST_TRANSACTION,
       COUNT(*) AS TOTAL_TRANSACTIONS,
       ROUND(MIN(AMOUNT), 2) AS MIN_AMOUNT,
       ROUND(AVG(AMOUNT), 2) AS AVG_AMOUNT,
       ROUND(MAX(AMOUNT), 2) AS MAX_AMOUNT
FROM TRANSACTIONS;

-- 3. Ensure important dimension references exist for transaction rows.
-- Expected result: zero missing references when all imports and FKs succeeded.
SELECT
    SUM(CASE WHEN T.CUSTOMER_ID IS NOT NULL AND C.CUSTOMER_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_CUSTOMERS,
    SUM(CASE WHEN T.MERCHANT_ID IS NOT NULL AND M.MERCHANT_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_MERCHANTS,
    SUM(CASE WHEN T.DEVICE_ID IS NOT NULL AND D.DEVICE_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_DEVICES
FROM TRANSACTIONS T
LEFT JOIN CUSTOMERS C ON C.CUSTOMER_ID = T.CUSTOMER_ID
LEFT JOIN MERCHANTS M ON M.MERCHANT_ID = T.MERCHANT_ID
LEFT JOIN DEVICES D ON D.DEVICE_ID = T.DEVICE_ID;

-- 4. Inspect transaction status values and counts.
SELECT STATUS, COUNT(*) AS ROW_COUNT
FROM TRANSACTIONS
GROUP BY STATUS
ORDER BY ROW_COUNT DESC;

-- 5. Inspect chargeback outcomes and loss amounts.
SELECT STATUS, COUNT(*) AS CASE_COUNT,
       ROUND(SUM(CHARGEBACK_AMOUNT), 2) AS TOTAL_AMOUNT
FROM CHARGEBACKS
GROUP BY STATUS
ORDER BY CASE_COUNT DESC;

-- 6. Inspect alerts by rule and review status.
SELECT RULE_TRIGGERED, REVIEWER_STATUS, RESOLUTION,
       COUNT(*) AS ALERT_COUNT,
       ROUND(AVG(RISK_SCORE), 2) AS AVG_RISK_SCORE
FROM FRAUD_ALERTS
GROUP BY RULE_TRIGGERED, REVIEWER_STATUS, RESOLUTION
ORDER BY ALERT_COUNT DESC;

-- 7. Quick sanity check: transactions without any fraud-alert row.
SELECT COUNT(*) AS TRANSACTIONS_WITHOUT_ALERT
FROM TRANSACTIONS T
WHERE NOT EXISTS (
    SELECT 1 FROM FRAUD_ALERTS A
    WHERE A.TRANSACTION_ID = T.TRANSACTION_ID
);
