-- Approve one extracted candidate and save it as an authoritative financial value.
-- This procedure does not COMMIT; the calling session controls the transaction.

CREATE OR REPLACE PROCEDURE VALIDATE_AND_SAVE_FINANCIAL_VALUE (
    P_RAW_DATA_ID    IN NUMBER,
    P_APPROVED_VALUE IN NUMBER,
    P_VALIDATED_BY   IN VARCHAR2
)
AS
    V_PERIOD_ID      NUMBER;
    V_ITEM_ID        NUMBER;
    V_STATUS         VARCHAR2(12);
    V_ITEM_CODE      VARCHAR2(50);
BEGIN
    IF P_APPROVED_VALUE IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Approved value cannot be empty.');
    END IF;

    IF P_VALIDATED_BY IS NULL OR LENGTH(TRIM(P_VALIDATED_BY)) = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Reviewer name is required.');
    END IF;

    SELECT PERIOD_ID, STANDARD_ITEM_ID, VALIDATION_STATUS
    INTO V_PERIOD_ID, V_ITEM_ID, V_STATUS
    FROM RAW_FINANCIAL_DATA
    WHERE RAW_DATA_ID = P_RAW_DATA_ID
    FOR UPDATE;

    IF V_STATUS = 'REJECTED' THEN
        RAISE_APPLICATION_ERROR(-20003, 'A rejected extraction candidate cannot be approved.');
    END IF;

    IF V_ITEM_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20004, 'Map this raw label to a standard financial item before approval.');
    END IF;

    SELECT ITEM_CODE
    INTO V_ITEM_CODE
    FROM FINANCIAL_ITEM
    WHERE ITEM_ID = V_ITEM_ID;

    IF P_APPROVED_VALUE < 0
       AND V_ITEM_CODE NOT IN ('NET_PROFIT', 'OPERATING_CASH_FLOW') THEN
        RAISE_APPLICATION_ERROR(-20005, 'Negative values are only accepted for net profit and operating cash flow.');
    END IF;

    IF V_ITEM_CODE = 'CURRENT_LIABILITIES' AND P_APPROVED_VALUE <= 0 THEN
        RAISE_APPLICATION_ERROR(-20006, 'Current liabilities must be greater than zero to calculate liquidity ratios.');
    END IF;

    MERGE INTO FINANCIAL_VALUE T
    USING (
        SELECT V_PERIOD_ID PERIOD_ID, V_ITEM_ID ITEM_ID FROM DUAL
    ) S
    ON (T.PERIOD_ID = S.PERIOD_ID AND T.ITEM_ID = S.ITEM_ID)
    WHEN MATCHED THEN UPDATE SET
        T.RAW_DATA_ID = P_RAW_DATA_ID,
        T.ITEM_VALUE = P_APPROVED_VALUE,
        T.VALIDATION_STATUS = 'MANUAL_REVIEWED',
        T.VALIDATED_BY = TRIM(P_VALIDATED_BY),
        T.VALIDATED_AT = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT (
        PERIOD_ID, ITEM_ID, RAW_DATA_ID, ITEM_VALUE,
        VALIDATION_STATUS, VALIDATED_BY, VALIDATED_AT
    ) VALUES (
        V_PERIOD_ID, V_ITEM_ID, P_RAW_DATA_ID, P_APPROVED_VALUE,
        'MANUAL_REVIEWED', TRIM(P_VALIDATED_BY), SYSTIMESTAMP
    );

    UPDATE RAW_FINANCIAL_DATA
    SET VALIDATION_STATUS = 'VALIDATED',
        REVIEWED_BY = TRIM(P_VALIDATED_BY),
        REVIEWED_AT = SYSTIMESTAMP
    WHERE RAW_DATA_ID = P_RAW_DATA_ID;
END;
