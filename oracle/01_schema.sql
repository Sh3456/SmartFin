-- SmartFin: Fintech Fraud Analytics — Oracle schema (Oracle 12c+)
-- Create tables in this order, then import the seven CSV datasets.
-- Boolean-like CSV values are kept as text ('True'/'False') for simple import.

CREATE TABLE LOCATIONS (
    LOCATION_ID VARCHAR2(50) PRIMARY KEY,
    COUNTRY VARCHAR2(100),
    REGION_STATE VARCHAR2(100),
    CITY VARCHAR2(100),
    ZIP_CODE VARCHAR2(20),
    RISK_SCORE NUMBER(5,2),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT CK_LOC_RISK CHECK (RISK_SCORE IS NULL OR RISK_SCORE BETWEEN 0 AND 100)
);

CREATE TABLE DEVICES (
    DEVICE_ID VARCHAR2(50) PRIMARY KEY,
    DEVICE_TYPE VARCHAR2(50),
    OS_NAME VARCHAR2(50),
    BROWSER VARCHAR2(50),
    IP_ADDRESS VARCHAR2(45),
    IS_VPN_PROXY VARCHAR2(5),
    LOCATION_ID VARCHAR2(50),
    FIRST_SEEN_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_DEV_LOC FOREIGN KEY (LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_DEV_VPN CHECK (IS_VPN_PROXY IS NULL OR UPPER(IS_VPN_PROXY) IN ('TRUE','FALSE','1','0','YES','NO'))
);

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID VARCHAR2(50) PRIMARY KEY,
    FIRST_NAME VARCHAR2(100),
    LAST_NAME VARCHAR2(100),
    EMAIL VARCHAR2(255) UNIQUE,
    PHONE_NUMBER VARCHAR2(20),
    ACCOUNT_STATUS VARCHAR2(20),
    KYC_VERIFIED VARCHAR2(5),
    ACCOUNT_CREATED_AT TIMESTAMP,
    PRIMARY_LOCATION_ID VARCHAR2(50),
    CONSTRAINT FK_CUST_LOC FOREIGN KEY (PRIMARY_LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_CUST_KYC CHECK (KYC_VERIFIED IS NULL OR UPPER(KYC_VERIFIED) IN ('TRUE','FALSE','1','0','YES','NO'))
);

CREATE TABLE MERCHANTS (
    MERCHANT_ID VARCHAR2(50) PRIMARY KEY,
    MERCHANT_NAME VARCHAR2(255),
    MCC_CODE VARCHAR2(4),
    MCC_DESCRIPTION VARCHAR2(100),
    BUSINESS_TYPE VARCHAR2(50),
    RISK_TIER VARCHAR2(20),
    ONBOARDING_DATE DATE,
    PRIMARY_LOCATION_ID VARCHAR2(50),
    CONSTRAINT FK_MERCH_LOC FOREIGN KEY (PRIMARY_LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID)
);

CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID VARCHAR2(50) PRIMARY KEY,
    CUSTOMER_ID VARCHAR2(50),
    MERCHANT_ID VARCHAR2(50),
    DEVICE_ID VARCHAR2(50),
    AMOUNT NUMBER(15,2) NOT NULL,
    CURRENCY VARCHAR2(3),
    TRANSACTION_TIMESTAMP TIMESTAMP NOT NULL,
    STATUS VARCHAR2(20),
    PAYMENT_METHOD VARCHAR2(50),
    CARD_NETWORK VARCHAR2(20),
    CVV_MATCH VARCHAR2(5),
    AVS_MATCH VARCHAR2(5),
    CONSTRAINT FK_TX_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT FK_TX_MERCH FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANTS(MERCHANT_ID),
    CONSTRAINT FK_TX_DEVICE FOREIGN KEY (DEVICE_ID) REFERENCES DEVICES(DEVICE_ID),
    CONSTRAINT CK_TX_AMOUNT CHECK (AMOUNT >= 0),
    CONSTRAINT CK_TX_CVV CHECK (CVV_MATCH IS NULL OR UPPER(CVV_MATCH) IN ('TRUE','FALSE','1','0','YES','NO')),
    CONSTRAINT CK_TX_AVS CHECK (AVS_MATCH IS NULL OR UPPER(AVS_MATCH) IN ('TRUE','FALSE','1','0','YES','NO'))
);

CREATE TABLE CHARGEBACKS (
    CHARGEBACK_ID VARCHAR2(50) PRIMARY KEY,
    TRANSACTION_ID VARCHAR2(50) NOT NULL,
    CHARGEBACK_DATE TIMESTAMP,
    REASON_CODE VARCHAR2(50),
    CHARGEBACK_AMOUNT NUMBER(15,2) NOT NULL,
    STATUS VARCHAR2(20),
    CONSTRAINT FK_CB_TX FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(TRANSACTION_ID),
    CONSTRAINT CK_CB_AMOUNT CHECK (CHARGEBACK_AMOUNT >= 0)
);

CREATE TABLE FRAUD_ALERTS (
    ALERT_ID VARCHAR2(50) PRIMARY KEY,
    TRANSACTION_ID VARCHAR2(50) NOT NULL,
    ALERT_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RULE_TRIGGERED VARCHAR2(100) NOT NULL,
    RISK_SCORE NUMBER(3) NOT NULL,
    REVIEWER_STATUS VARCHAR2(20) DEFAULT 'Unassigned',
    RESOLUTION VARCHAR2(50) DEFAULT 'Unresolved',
    CONSTRAINT FK_ALERT_TX FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(TRANSACTION_ID),
    CONSTRAINT CK_ALERT_SCORE CHECK (RISK_SCORE BETWEEN 0 AND 100)
);

CREATE INDEX IDX_TX_CUST_TIME ON TRANSACTIONS(CUSTOMER_ID, TRANSACTION_TIMESTAMP);
CREATE INDEX IDX_TX_MERCHANT ON TRANSACTIONS(MERCHANT_ID);
CREATE INDEX IDX_TX_DEVICE ON TRANSACTIONS(DEVICE_ID);
CREATE INDEX IDX_DEV_IP ON DEVICES(IP_ADDRESS);
CREATE INDEX IDX_CB_TX ON CHARGEBACKS(TRANSACTION_ID);
CREATE INDEX IDX_ALERT_STATUS ON FRAUD_ALERTS(REVIEWER_STATUS);
CREATE INDEX IDX_ALERT_RULE ON FRAUD_ALERTS(RULE_TRIGGERED);
