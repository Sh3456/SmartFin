-- SmartFin Oracle schema (Oracle Database 12c or later)
-- Run this script in SQL Developer while connected as your project schema user.
-- Scope: company statements, extracted candidates, and approved financial values.

CREATE TABLE COMPANY (
    COMPANY_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COMPANY_NAME    VARCHAR2(200) NOT NULL UNIQUE,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE FINANCIAL_PERIOD (
    PERIOD_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COMPANY_ID         NUMBER NOT NULL,
    FISCAL_YEAR        VARCHAR2(9) NOT NULL,
    STATEMENT_SCOPE    VARCHAR2(12) DEFAULT 'STANDALONE' NOT NULL,
    CURRENCY_CODE      CHAR(3) DEFAULT 'INR' NOT NULL,
    UNIT_LABEL         VARCHAR2(20) DEFAULT 'INR crore' NOT NULL,
    SOURCE_FILENAME    VARCHAR2(500),
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_PERIOD_COMPANY FOREIGN KEY (COMPANY_ID)
        REFERENCES COMPANY (COMPANY_ID),
    CONSTRAINT CK_PERIOD_SCOPE CHECK (STATEMENT_SCOPE IN ('STANDALONE', 'CONSOLIDATED')),
    CONSTRAINT CK_PERIOD_UNIT CHECK (UNIT_LABEL IN ('INR crore', 'INR lakh', 'INR million', 'INR')),
    CONSTRAINT UQ_FINANCIAL_PERIOD UNIQUE (COMPANY_ID, FISCAL_YEAR, STATEMENT_SCOPE)
);

CREATE TABLE FINANCIAL_ITEM (
    ITEM_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ITEM_CODE        VARCHAR2(50) NOT NULL UNIQUE,
    ITEM_NAME        VARCHAR2(200) NOT NULL,
    CATEGORY         VARCHAR2(30) NOT NULL,
    FORMULA_NOTES    VARCHAR2(1000),
    IS_ACTIVE        CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CK_ITEM_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- This table stores what the PDF extractor proposes. Rows stay pending
-- until someone reviews the label, value, year, scope, and unit.
CREATE TABLE RAW_FINANCIAL_DATA (
    RAW_DATA_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PERIOD_ID            NUMBER NOT NULL,
    RAW_ITEM_LABEL       VARCHAR2(500) NOT NULL,
    STANDARD_ITEM_ID     NUMBER,
    EXTRACTED_VALUE      NUMBER(20,4),
    SOURCE_PAGE          NUMBER,
    SOURCE_SNIPPET       CLOB,
    EXTRACTION_METHOD    VARCHAR2(40),
    CONFIDENCE_SCORE     NUMBER(5,4),
    VALIDATION_STATUS    VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
    REVIEWED_BY          VARCHAR2(128),
    REVIEWED_AT          TIMESTAMP,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RAW_PERIOD FOREIGN KEY (PERIOD_ID)
        REFERENCES FINANCIAL_PERIOD (PERIOD_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RAW_ITEM FOREIGN KEY (STANDARD_ITEM_ID)
        REFERENCES FINANCIAL_ITEM (ITEM_ID),
    CONSTRAINT CK_RAW_PAGE CHECK (SOURCE_PAGE IS NULL OR SOURCE_PAGE > 0),
    CONSTRAINT CK_RAW_CONFIDENCE CHECK (
        CONFIDENCE_SCORE IS NULL OR CONFIDENCE_SCORE BETWEEN 0 AND 1
    ),
    CONSTRAINT CK_RAW_STATUS CHECK (
        VALIDATION_STATUS IN ('PENDING', 'VALIDATED', 'REJECTED')
    )
);

-- Only reviewed/approved numbers belong in FINANCIAL_VALUE.
CREATE TABLE FINANCIAL_VALUE (
    FINANCIAL_VALUE_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PERIOD_ID             NUMBER NOT NULL,
    ITEM_ID               NUMBER NOT NULL,
    RAW_DATA_ID           NUMBER,
    ITEM_VALUE            NUMBER(20,4) NOT NULL,
    VALIDATION_STATUS     VARCHAR2(20) DEFAULT 'MANUAL_REVIEWED' NOT NULL,
    VALIDATED_BY          VARCHAR2(128) NOT NULL,
    VALIDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_VALUE_PERIOD FOREIGN KEY (PERIOD_ID)
        REFERENCES FINANCIAL_PERIOD (PERIOD_ID) ON DELETE CASCADE,
    CONSTRAINT FK_VALUE_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES FINANCIAL_ITEM (ITEM_ID),
    CONSTRAINT FK_VALUE_RAW FOREIGN KEY (RAW_DATA_ID)
        REFERENCES RAW_FINANCIAL_DATA (RAW_DATA_ID),
    CONSTRAINT UQ_VALUE_PERIOD_ITEM UNIQUE (PERIOD_ID, ITEM_ID),
    CONSTRAINT UQ_VALUE_RAW UNIQUE (RAW_DATA_ID),
    CONSTRAINT CK_VALUE_STATUS CHECK (
        VALIDATION_STATUS IN ('VALIDATED', 'MANUAL_REVIEWED')
    )
);

CREATE INDEX IDX_PERIOD_COMPANY_YEAR
    ON FINANCIAL_PERIOD (COMPANY_ID, FISCAL_YEAR);

CREATE INDEX IDX_RAW_PERIOD_STATUS
    ON RAW_FINANCIAL_DATA (PERIOD_ID, VALIDATION_STATUS);

CREATE INDEX IDX_VALUE_ITEM_PERIOD
    ON FINANCIAL_VALUE (ITEM_ID, PERIOD_ID);

-- View: one row per company/report, with the key liquidity inputs.
CREATE OR REPLACE VIEW V_COMPANY_LIQUIDITY AS
SELECT
    C.COMPANY_ID,
    C.COMPANY_NAME,
    P.PERIOD_ID,
    P.FISCAL_YEAR,
    P.STATEMENT_SCOPE,
    P.CURRENCY_CODE,
    P.UNIT_LABEL,
    MAX(CASE WHEN I.ITEM_CODE = 'CURRENT_ASSETS' THEN V.ITEM_VALUE END) AS CURRENT_ASSETS,
    MAX(CASE WHEN I.ITEM_CODE = 'CURRENT_LIABILITIES' THEN V.ITEM_VALUE END) AS CURRENT_LIABILITIES,
    MAX(CASE WHEN I.ITEM_CODE = 'INVENTORY' THEN V.ITEM_VALUE END) AS INVENTORY
FROM COMPANY C
JOIN FINANCIAL_PERIOD P ON P.COMPANY_ID = C.COMPANY_ID
LEFT JOIN FINANCIAL_VALUE V ON V.PERIOD_ID = P.PERIOD_ID
LEFT JOIN FINANCIAL_ITEM I ON I.ITEM_ID = V.ITEM_ID
GROUP BY
    C.COMPANY_ID, C.COMPANY_NAME, P.PERIOD_ID, P.FISCAL_YEAR,
    P.STATEMENT_SCOPE, P.CURRENCY_CODE, P.UNIT_LABEL;
