-- SmartFin Oracle analysis queries
-- Run these after 01_schema.sql and 02_seed_financial_items.sql.

-- 1. Companies and saved reporting periods.
SELECT C.COMPANY_NAME, P.FISCAL_YEAR, P.STATEMENT_SCOPE,
       P.CURRENCY_CODE, P.UNIT_LABEL, P.SOURCE_FILENAME
FROM COMPANY C
JOIN FINANCIAL_PERIOD P ON P.COMPANY_ID = C.COMPANY_ID
ORDER BY C.COMPANY_NAME, P.FISCAL_YEAR DESC, P.STATEMENT_SCOPE;

-- 2. Review queue: candidate figures that have not been approved yet.
SELECT R.RAW_DATA_ID, C.COMPANY_NAME, P.FISCAL_YEAR, P.STATEMENT_SCOPE,
       I.ITEM_CODE, R.RAW_ITEM_LABEL, R.EXTRACTED_VALUE,
       P.UNIT_LABEL, R.SOURCE_PAGE, R.CONFIDENCE_SCORE, R.VALIDATION_STATUS
FROM RAW_FINANCIAL_DATA R
JOIN FINANCIAL_PERIOD P ON P.PERIOD_ID = R.PERIOD_ID
JOIN COMPANY C ON C.COMPANY_ID = P.COMPANY_ID
LEFT JOIN FINANCIAL_ITEM I ON I.ITEM_ID = R.STANDARD_ITEM_ID
WHERE R.VALIDATION_STATUS = 'PENDING'
ORDER BY C.COMPANY_NAME, P.FISCAL_YEAR, R.RAW_DATA_ID;

-- 3. Approved financial figures for every company and period.
SELECT C.COMPANY_NAME, P.FISCAL_YEAR, P.STATEMENT_SCOPE,
       I.ITEM_CODE, I.ITEM_NAME, V.ITEM_VALUE, P.UNIT_LABEL,
       V.VALIDATION_STATUS, V.VALIDATED_BY, V.VALIDATED_AT
FROM FINANCIAL_VALUE V
JOIN FINANCIAL_PERIOD P ON P.PERIOD_ID = V.PERIOD_ID
JOIN COMPANY C ON C.COMPANY_ID = P.COMPANY_ID
JOIN FINANCIAL_ITEM I ON I.ITEM_ID = V.ITEM_ID
ORDER BY C.COMPANY_NAME, P.FISCAL_YEAR, I.ITEM_CODE;

-- 4. Calculate the three MVP liquidity metrics.
-- Quick ratio follows the project definition: (Current assets - inventory) / current liabilities.
WITH S AS (
    SELECT COMPANY_ID, COMPANY_NAME, PERIOD_ID, FISCAL_YEAR,
           STATEMENT_SCOPE, UNIT_LABEL, CURRENT_ASSETS, CURRENT_LIABILITIES,
           NVL(INVENTORY, 0) AS INVENTORY
    FROM V_COMPANY_LIQUIDITY
)
SELECT COMPANY_NAME, FISCAL_YEAR, STATEMENT_SCOPE, UNIT_LABEL,
       CURRENT_ASSETS, CURRENT_LIABILITIES, INVENTORY,
       ROUND(CURRENT_ASSETS / NULLIF(CURRENT_LIABILITIES, 0), 2) AS CURRENT_RATIO,
       ROUND((CURRENT_ASSETS - INVENTORY) / NULLIF(CURRENT_LIABILITIES, 0), 2) AS QUICK_RATIO,
       CURRENT_ASSETS - CURRENT_LIABILITIES AS WORKING_CAPITAL
FROM S
ORDER BY COMPANY_NAME, FISCAL_YEAR, STATEMENT_SCOPE;

-- 5. Compare current ratio year-over-year for each company and scope.
WITH R AS (
    SELECT COMPANY_ID, COMPANY_NAME, FISCAL_YEAR, STATEMENT_SCOPE,
           ROUND(CURRENT_ASSETS / NULLIF(CURRENT_LIABILITIES, 0), 2) AS CURRENT_RATIO
    FROM V_COMPANY_LIQUIDITY
)
SELECT COMPANY_NAME, FISCAL_YEAR, STATEMENT_SCOPE, CURRENT_RATIO,
       LAG(CURRENT_RATIO) OVER (
           PARTITION BY COMPANY_ID, STATEMENT_SCOPE
           ORDER BY FISCAL_YEAR
       ) AS PREVIOUS_PERIOD_RATIO
FROM R
ORDER BY COMPANY_NAME, STATEMENT_SCOPE, FISCAL_YEAR;
