-- SmartFin: Fintech Fraud Analytics — Oracle SQL examples.
-- Run after schema creation and CSV import. Oracle 12c+.
-- Bind variables in query 1 can be entered as YYYY-MM-DD.

-- 1. Transaction KPIs for a selected date range.
SELECT COUNT(*) AS total_transactions,
       SUM(CASE WHEN UPPER(STATUS) = 'APPROVED' THEN 1 ELSE 0 END) AS approved_transactions,
       SUM(CASE WHEN UPPER(STATUS) = 'DECLINED' THEN 1 ELSE 0 END) AS declined_transactions,
       ROUND(SUM(CASE WHEN UPPER(STATUS) = 'APPROVED' THEN AMOUNT ELSE 0 END), 2) AS approved_value,
       ROUND(100 * SUM(CASE WHEN UPPER(STATUS) = 'APPROVED' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*), 0), 2) AS approval_rate_pct
FROM TRANSACTIONS
WHERE TRANSACTION_TIMESTAMP >= TO_TIMESTAMP(:start_date, 'YYYY-MM-DD')
  AND TRANSACTION_TIMESTAMP < TO_TIMESTAMP(:end_date, 'YYYY-MM-DD') + INTERVAL '1' DAY;

-- 2. Payment status distribution.
SELECT STATUS, COUNT(*) AS transaction_count,
       ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 2) AS percentage_of_all
FROM TRANSACTIONS
GROUP BY STATUS
ORDER BY transaction_count DESC;

-- 3. Merchants with the most declined transactions (possible card-testing signal).
SELECT M.MERCHANT_ID, M.MERCHANT_NAME, COUNT(*) AS declined_count
FROM TRANSACTIONS T JOIN MERCHANTS M ON M.MERCHANT_ID = T.MERCHANT_ID
WHERE UPPER(T.STATUS) = 'DECLINED'
GROUP BY M.MERCHANT_ID, M.MERCHANT_NAME
ORDER BY declined_count DESC
FETCH FIRST 10 ROWS ONLY;

-- 4. Approval rates by VPN/proxy use.
WITH DEVICE_TX AS (
    SELECT CASE
             WHEN UPPER(D.IS_VPN_PROXY) IN ('TRUE','1','YES') THEN 'VPN/Proxy'
             WHEN UPPER(D.IS_VPN_PROXY) IN ('FALSE','0','NO') THEN 'No VPN/Proxy'
             ELSE 'Unknown'
           END AS connection_type,
           T.STATUS
    FROM TRANSACTIONS T JOIN DEVICES D ON D.DEVICE_ID = T.DEVICE_ID
)
SELECT connection_type, COUNT(*) AS total_transactions,
       SUM(CASE WHEN UPPER(STATUS) = 'APPROVED' THEN 1 ELSE 0 END) AS approved_transactions,
       ROUND(100 * SUM(CASE WHEN UPPER(STATUS) = 'APPROVED' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*), 0), 2) AS approval_rate_pct
FROM DEVICE_TX
GROUP BY connection_type
ORDER BY total_transactions DESC;

-- 5. Unverified customers with high approved lifetime spend.
SELECT C.CUSTOMER_ID, C.FIRST_NAME, C.LAST_NAME,
       ROUND(SUM(T.AMOUNT), 2) AS approved_lifetime_spend,
       COUNT(*) AS approved_transaction_count
FROM CUSTOMERS C JOIN TRANSACTIONS T ON T.CUSTOMER_ID = C.CUSTOMER_ID
WHERE UPPER(C.KYC_VERIFIED) IN ('FALSE','0','NO')
  AND UPPER(T.STATUS) = 'APPROVED'
GROUP BY C.CUSTOMER_ID, C.FIRST_NAME, C.LAST_NAME
HAVING SUM(T.AMOUNT) > 10000
ORDER BY approved_lifetime_spend DESC;

-- 6. Monthly chargeback losses.
SELECT TRUNC(CHARGEBACK_DATE, 'MM') AS loss_month,
       COUNT(*) AS lost_chargebacks,
       ROUND(SUM(CHARGEBACK_AMOUNT), 2) AS total_loss
FROM CHARGEBACKS
WHERE UPPER(STATUS) = 'LOST'
GROUP BY TRUNC(CHARGEBACK_DATE, 'MM')
ORDER BY loss_month;

-- 7. Chargebacks grouped by reason code.
SELECT REASON_CODE, COUNT(*) AS incident_count,
       ROUND(SUM(CHARGEBACK_AMOUNT), 2) AS disputed_value
FROM CHARGEBACKS
GROUP BY REASON_CODE
ORDER BY disputed_value DESC;

-- 8. Merchant chargeback rate. Aggregate the two sides first to avoid
-- inflating transaction counts when a transaction has multiple dispute rows.
WITH TX_COUNTS AS (
    SELECT MERCHANT_ID, COUNT(*) AS TRANSACTION_COUNT
    FROM TRANSACTIONS GROUP BY MERCHANT_ID
),
CB_COUNTS AS (
    SELECT T.MERCHANT_ID,
           COUNT(DISTINCT C.TRANSACTION_ID) AS CHARGEBACK_TRANSACTIONS,
           SUM(CASE WHEN UPPER(C.STATUS) = 'LOST' THEN C.CHARGEBACK_AMOUNT ELSE 0 END) AS LOST_AMOUNT
    FROM TRANSACTIONS T JOIN CHARGEBACKS C ON C.TRANSACTION_ID = T.TRANSACTION_ID
    GROUP BY T.MERCHANT_ID
)
SELECT M.MERCHANT_ID, M.MERCHANT_NAME, TX.TRANSACTION_COUNT,
       NVL(CB.CHARGEBACK_TRANSACTIONS, 0) AS CHARGEBACK_TRANSACTIONS,
       ROUND(100 * NVL(CB.CHARGEBACK_TRANSACTIONS, 0) / NULLIF(TX.TRANSACTION_COUNT, 0), 3) AS chargeback_rate_pct,
       ROUND(NVL(CB.LOST_AMOUNT, 0), 2) AS lost_amount,
       CASE
         WHEN 100 * NVL(CB.CHARGEBACK_TRANSACTIONS, 0) / NULLIF(TX.TRANSACTION_COUNT, 0) >= 2 THEN 'HIGH - REVIEW'
         WHEN 100 * NVL(CB.CHARGEBACK_TRANSACTIONS, 0) / NULLIF(TX.TRANSACTION_COUNT, 0) >= 1 THEN 'MEDIUM - MONITOR'
         ELSE 'LOWER - MONITOR'
       END AS suggested_risk_tier
FROM MERCHANTS M JOIN TX_COUNTS TX ON TX.MERCHANT_ID = M.MERCHANT_ID
LEFT JOIN CB_COUNTS CB ON CB.MERCHANT_ID = M.MERCHANT_ID
WHERE TX.TRANSACTION_COUNT >= 100
ORDER BY chargeback_rate_pct DESC NULLS LAST;

-- 9. Rule precision among closed/reviewed alerts.
SELECT RULE_TRIGGERED, COUNT(*) AS reviewed_alerts,
       SUM(CASE WHEN RESOLUTION = 'True Positive (Fraud)' THEN 1 ELSE 0 END) AS confirmed_fraud,
       ROUND(100 * SUM(CASE WHEN RESOLUTION = 'True Positive (Fraud)' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(*), 0), 2) AS precision_pct
FROM FRAUD_ALERTS
WHERE UPPER(REVIEWER_STATUS) = 'CLOSED'
GROUP BY RULE_TRIGGERED
ORDER BY reviewed_alerts DESC;

-- 10. AVS mismatch on declined payments.
SELECT C.CUSTOMER_ID, C.EMAIL, COUNT(*) AS declined_avs_mismatches
FROM TRANSACTIONS T JOIN CUSTOMERS C ON C.CUSTOMER_ID = T.CUSTOMER_ID
WHERE UPPER(T.AVS_MATCH) IN ('FALSE','0','NO') AND UPPER(T.STATUS) = 'DECLINED'
GROUP BY C.CUSTOMER_ID, C.EMAIL
ORDER BY declined_avs_mismatches DESC
FETCH FIRST 20 ROWS ONLY;

-- 11. Latest transaction per customer: ROW_NUMBER.
WITH RANKED AS (
    SELECT T.*,
           ROW_NUMBER() OVER (
               PARTITION BY CUSTOMER_ID
               ORDER BY TRANSACTION_TIMESTAMP DESC, TRANSACTION_ID
           ) AS RN
    FROM TRANSACTIONS T
)
SELECT CUSTOMER_ID, TRANSACTION_ID, AMOUNT, STATUS, TRANSACTION_TIMESTAMP
FROM RANKED WHERE RN = 1;

-- 12. Top three approved transaction amounts per merchant: DENSE_RANK.
WITH RANKED AS (
    SELECT T.MERCHANT_ID, T.TRANSACTION_ID, T.CUSTOMER_ID, T.AMOUNT,
           DENSE_RANK() OVER (PARTITION BY T.MERCHANT_ID ORDER BY T.AMOUNT DESC) AS AMOUNT_RANK
    FROM TRANSACTIONS T WHERE UPPER(T.STATUS) = 'APPROVED'
)
SELECT M.MERCHANT_NAME, R.TRANSACTION_ID, R.CUSTOMER_ID, R.AMOUNT, R.AMOUNT_RANK
FROM RANKED R JOIN MERCHANTS M ON M.MERCHANT_ID = R.MERCHANT_ID
WHERE R.AMOUNT_RANK <= 3
ORDER BY M.MERCHANT_NAME, R.AMOUNT_RANK;

-- 13. Cumulative monthly chargeback loss: SUM OVER.
WITH MONTHLY AS (
    SELECT TRUNC(CHARGEBACK_DATE, 'MM') AS LOSS_MONTH, SUM(CHARGEBACK_AMOUNT) AS MONTHLY_LOSS
    FROM CHARGEBACKS WHERE UPPER(STATUS) = 'LOST'
    GROUP BY TRUNC(CHARGEBACK_DATE, 'MM')
)
SELECT LOSS_MONTH, MONTHLY_LOSS,
       SUM(MONTHLY_LOSS) OVER (ORDER BY LOSS_MONTH) AS CUMULATIVE_LOSS
FROM MONTHLY ORDER BY LOSS_MONTH;

-- 14. High-velocity candidates: five or more approved transactions in ten minutes.
WITH VELOCITY AS (
    SELECT T.CUSTOMER_ID, T.TRANSACTION_ID, T.AMOUNT, T.TRANSACTION_TIMESTAMP,
           COUNT(*) OVER (
             PARTITION BY T.CUSTOMER_ID ORDER BY CAST(T.TRANSACTION_TIMESTAMP AS DATE)
             RANGE BETWEEN NUMTODSINTERVAL(10, 'MINUTE') PRECEDING AND CURRENT ROW
           ) AS TRANSACTIONS_LAST_10_MIN,
           SUM(T.AMOUNT) OVER (
             PARTITION BY T.CUSTOMER_ID ORDER BY CAST(T.TRANSACTION_TIMESTAMP AS DATE)
             RANGE BETWEEN NUMTODSINTERVAL(10, 'MINUTE') PRECEDING AND CURRENT ROW
           ) AS AMOUNT_LAST_10_MIN
    FROM TRANSACTIONS T WHERE UPPER(T.STATUS) = 'APPROVED'
)
SELECT CUSTOMER_ID, TRANSACTION_ID, AMOUNT, TRANSACTION_TIMESTAMP,
       TRANSACTIONS_LAST_10_MIN, AMOUNT_LAST_10_MIN
FROM VELOCITY
WHERE TRANSACTIONS_LAST_10_MIN >= 5
ORDER BY CUSTOMER_ID, TRANSACTION_TIMESTAMP;

-- 15. Devices shared by five or more distinct customers (possible device farming).
SELECT D.DEVICE_ID, D.DEVICE_TYPE, D.IP_ADDRESS,
       COUNT(DISTINCT T.CUSTOMER_ID) AS DISTINCT_CUSTOMERS,
       COUNT(T.TRANSACTION_ID) AS TRANSACTION_COUNT
FROM DEVICES D JOIN TRANSACTIONS T ON T.DEVICE_ID = D.DEVICE_ID
GROUP BY D.DEVICE_ID, D.DEVICE_TYPE, D.IP_ADDRESS
HAVING COUNT(DISTINCT T.CUSTOMER_ID) >= 5
ORDER BY DISTINCT_CUSTOMERS DESC, TRANSACTION_COUNT DESC;

-- 16. Customers appearing in two countries within one hour (coarse heuristic;
-- the dataset has city/country labels, not geographic coordinates).
WITH TRAVEL AS (
    SELECT T.CUSTOMER_ID, T.TRANSACTION_ID, T.TRANSACTION_TIMESTAMP, L.COUNTRY,
           LAG(L.COUNTRY) OVER (
             PARTITION BY T.CUSTOMER_ID ORDER BY T.TRANSACTION_TIMESTAMP
           ) AS PREVIOUS_COUNTRY,
           LAG(T.TRANSACTION_TIMESTAMP) OVER (
             PARTITION BY T.CUSTOMER_ID ORDER BY T.TRANSACTION_TIMESTAMP
           ) AS PREVIOUS_TIMESTAMP
    FROM TRANSACTIONS T
    JOIN DEVICES D ON D.DEVICE_ID = T.DEVICE_ID
    JOIN LOCATIONS L ON L.LOCATION_ID = D.LOCATION_ID
)
SELECT CUSTOMER_ID, TRANSACTION_ID, PREVIOUS_COUNTRY, COUNTRY,
       PREVIOUS_TIMESTAMP, TRANSACTION_TIMESTAMP
FROM TRAVEL
WHERE PREVIOUS_COUNTRY IS NOT NULL
  AND COUNTRY <> PREVIOUS_COUNTRY
  AND TRANSACTION_TIMESTAMP - PREVIOUS_TIMESTAMP <= INTERVAL '60' MINUTE
ORDER BY CUSTOMER_ID, TRANSACTION_TIMESTAMP;
